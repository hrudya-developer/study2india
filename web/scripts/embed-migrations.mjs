// Copies the SQL migrations in drizzle/ into a TypeScript module, so they ship inside the
// compiled app. Hostinger deploys only the build output, not the drizzle/ folder.
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..");
const journal = JSON.parse(readFileSync(path.join(root, "drizzle/meta/_journal.json"), "utf8"));

const migrations = journal.entries.map((e) => {
  const sqlText = readFileSync(path.join(root, "drizzle", `${e.tag}.sql`), "utf8");
  const statements = sqlText
    .split("--> statement-breakpoint")
    .map((s) => s.trim())
    .filter(Boolean);
  return { tag: e.tag, statements };
});

const out = `// Generated by scripts/embed-migrations.mjs from drizzle/. Do not edit by hand.
export const MIGRATIONS: { tag: string; statements: string[] }[] = ${JSON.stringify(migrations, null, 2)};
`;
writeFileSync(path.join(root, "lib/db/migrations.generated.ts"), out);
console.log(`Embedded ${migrations.length} migration(s)`);
