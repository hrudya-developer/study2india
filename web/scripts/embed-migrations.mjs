// Copies the SQL migrations in drizzle/ into a TypeScript module, so they ship inside the
// compiled app. Hostinger deploys only the build output, not the drizzle/ folder.
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..");
const journal = JSON.parse(readFileSync(path.join(root, "drizzle/meta/_journal.json"), "utf8"));

const migrations = journal.entries.map((e) => {
  const sqlText = readFileSync(path.join(root, "drizzle", `${e.tag}.sql`), "utf8");
  const statements = sqlText
    .split("--> statement-breakpoint")
    .map((s) => s.trim())
    .filter(Boolean);
  return { tag: e.tag, statements };
});

const out = `// Generated by scripts/embed-migrations.mjs from drizzle/. Do not edit by hand.
export const MIGRATIONS: { tag: string; statements: string[] }[] = ${JSON.stringify(migrations, null, 2)};
`;
writeFileSync(path.join(root, "lib/db/migrations.generated.ts"), out);
console.log(`Embedded ${migrations.length} migration(s)`);

// Official data files (data/nirf/<year>/*.json) are embedded the same way, with a content hash
// so startup can skip any file it has already loaded.
import { readdirSync, existsSync, statSync } from "node:fs";
import { createHash } from "node:crypto";

const nirfRoot = path.join(root, "data", "nirf");
const files = [];
if (existsSync(nirfRoot)) {
  for (const year of readdirSync(nirfRoot).filter((d) => statSync(path.join(nirfRoot, d)).isDirectory()).sort()) {
    for (const f of readdirSync(path.join(nirfRoot, year)).filter((x) => x.endsWith(".json") && !x.startsWith("_")).sort()) {
      const text = readFileSync(path.join(nirfRoot, year, f), "utf8");
      files.push({ tag: `nirf-${year}-${f.replace(/\.json$/, "")}`, hash: createHash("sha256").update(text).digest("hex").slice(0, 16), data: JSON.parse(text) });
    }
  }
}
// Council lists (data/nmc/*.json): one file per course. links.json maps council codes to NIRF codes
// checked by hand; it is part of every file's hash so a changed link reloads the lists.
const councilRoot = path.join(root, "data", "nmc");
const councilFiles = [];
let links = {};
if (existsSync(councilRoot)) {
  const linksPath = path.join(councilRoot, "links.json");
  const linksText = existsSync(linksPath) ? readFileSync(linksPath, "utf8") : "{}";
  links = JSON.parse(linksText).links ?? {};
  for (const f of readdirSync(councilRoot).filter((x) => x.endsWith(".json") && x !== "links.json").sort()) {
    const text = readFileSync(path.join(councilRoot, f), "utf8");
    councilFiles.push({ tag: `nmc-${f.replace(/\.json$/, "")}`, hash: createHash("sha256").update(text).update(linksText).digest("hex").slice(0, 16), data: JSON.parse(text) });
  }
}

// Other councils' college lists (data/councils/*.json) share one format; see seedCouncils in lib/bootstrap.ts.
const councilsRoot = path.join(root, "data", "councils");
const councilLists = [];
if (existsSync(councilsRoot)) {
  for (const f of readdirSync(councilsRoot).filter((x) => x.endsWith(".json")).sort()) {
    const text = readFileSync(path.join(councilsRoot, f), "utf8");
    councilLists.push({ tag: `council-${f.replace(/\.json$/, "")}`, hash: createHash("sha256").update(text).digest("hex").slice(0, 16), data: JSON.parse(text) });
  }
}

// Admission cutoff files (data/cutoffs/*.json): opening and closing ranks per offering; see lib/seed/cutoffs.ts.
const cutoffsRoot = path.join(root, "data", "cutoffs");
const cutoffFiles = [];
if (existsSync(cutoffsRoot)) {
  for (const f of readdirSync(cutoffsRoot).filter((x) => x.endsWith(".json")).sort()) {
    const text = readFileSync(path.join(cutoffsRoot, f), "utf8");
    cutoffFiles.push({ tag: `cutoffs-${f.replace(/\.json$/, "")}`, hash: createHash("sha256").update(text).digest("hex").slice(0, 16), data: JSON.parse(text) });
  }
}

// A JS string literal holding the JSON text, for JSON.parse in the generated module.
const asJsonString = (value) => JSON.stringify(JSON.stringify(value));

writeFileSync(
  path.join(root, "lib/db/seed-data.generated.ts"),
  `// Generated by scripts/embed-migrations.mjs from data/nirf/, data/nmc/, data/councils/ and data/cutoffs/. Do not edit by hand.\n` +
    `// The large lists are embedded as JSON strings and parsed at load: as object literals they make\n` +
    `// TypeScript infer a union type too complex to represent (TS2590), and JSON.parse is faster to load.\n` +
    `type DataFile = { tag: string; hash: string; data: any };\n` +
    `export const NIRF_FILES: DataFile[] = JSON.parse(${asJsonString(files)});\n` +
    `export const NMC_FILES: DataFile[] = JSON.parse(${asJsonString(councilFiles)});\n` +
    `export const NMC_LINKS: Record<string, string> = ${JSON.stringify(links)};\n` +
    `export const COUNCIL_FILES: DataFile[] = JSON.parse(${asJsonString(councilLists)});\n` +
    `export const CUTOFF_FILES: DataFile[] = JSON.parse(${asJsonString(cutoffFiles)});\n`,
);
console.log(`Embedded ${files.length} NIRF file(s), ${councilFiles.length} NMC list(s), ${councilLists.length} other council list(s) and ${cutoffFiles.length} cutoff file(s)`);
