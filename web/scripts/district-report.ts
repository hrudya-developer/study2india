/**
 * Writes docs/district-mapping.md: every raw district value (and the city values used when there
 * is no usable district), the official district the normaliser maps it to, and how many
 * institutions carry it. Read-only. Run with `npx tsx scripts/district-report.ts` against a
 * loaded database (DATABASE_URL); the raw values come from the embedded council lists.
 */
import "dotenv/config";
import { writeFileSync } from "node:fs";
import path from "node:path";
import { planDistricts } from "../lib/bootstrap";
import { STATES } from "../data/reference";
import { DISTRICTS_SOURCE } from "../data/districts";
import { DISTRICT_NORMALISER_VERSION } from "../lib/districts";

type Row = { state: string; raw: string; field: "district" | "city"; district: string | null; match: string; n: number };

const MATCH_NOTE: Record<string, string> = {
  exact: "official spelling",
  normalised: "same name once case, spacing, punctuation and \"District\" are ignored",
  alias: "misspelling or former name, checked by hand",
  town: "town inside one district, checked by hand",
  part: "compound value; its parts agree on one district",
  ambiguous: "split district or place across several districts: not mapped",
  "city-spans-districts": "metro city whose colleges lie in several districts: not mapped as a city",
  "other-state": "a district of another state: not mapped",
  unknown: "not a district or known town: not mapped",
};

const esc = (s: string) => s.replace(/\|/g, "\\|");

async function main() {
  const plan = await planDistricts();
  const stateName = new Map(STATES.map((s) => [s.code, s.name]));
  const rowsByKey = new Map<string, Row>();
  for (const p of plan) {
    const state = (p.stateCode && stateName.get(p.stateCode)) || "(no state)";
    const hasDistrictHit = p.tried.some((t) => t.field === "district" && t.district);
    for (const t of p.tried) {
      // City values are listed only where the district column gave nothing usable.
      if (t.field === "city" && hasDistrictHit) continue;
      const k = `${state}\u0000${t.field}\u0000${t.raw}`;
      const row = rowsByKey.get(k) ?? { state, raw: t.raw, field: t.field, district: t.district, match: t.match, n: 0 };
      row.n++;
      rowsByKey.set(k, row);
    }
  }
  const all = [...rowsByKey.values()].sort((a, b) => a.state.localeCompare(b.state) || a.field.localeCompare(b.field) || a.raw.localeCompare(b.raw));
  const districtRows = all.filter((r) => r.field === "district");
  const cityRows = all.filter((r) => r.field === "city");
  const unresolved = all.filter((r) => !r.district);
  const counts = (list: Row[]) => {
    const m = new Map<string, number>();
    for (const r of list) m.set(r.match, (m.get(r.match) ?? 0) + 1);
    return [...m].sort((a, b) => b[1] - a[1]).map(([k, v]) => `${k} ${v}`).join(", ");
  };
  const finalPairs = new Set(plan.filter((p) => p.next).map((p) => `${p.stateCode}\u0000${p.next}`));

  const out: string[] = [];
  out.push("# District mapping audit", "");
  out.push(
    `Generated by \`scripts/district-report.ts\` (normaliser v${DISTRICT_NORMALISER_VERSION}). Official names: data/districts.ts, ` +
      `${DISTRICTS_SOURCE.publisher}, retrieved ${DISTRICTS_SOURCE.retrieved}. Matching code: lib/districts.ts.`,
    "",
  );
  out.push("How a value is mapped, in order: the official name after ignoring case, spacing, punctuation and a leading or trailing \"District\"/\"Dist.\"; the hand-checked alias list (misspellings and renames); the hand-checked list of towns that lie wholly inside one district; for compound values (\"Nitte, Udupi\", \"Prayagraj (Allahabad)\") each part, when all parts agree. Values that are split districts, places across several districts, districts of another state or unknown are not mapped, so they stay out of the district filter.", "");
  out.push("Each institution takes the first value that maps: the district from each council list that names it (AICTE, DCI, INC, NCH, NCISM, PCI, VCI, in that order), then its city, then the councils' city values. A metro city given only as the city (Hyderabad, Chennai, Kolkata, Bengaluru, Delhi) is not mapped, because colleges given that city lie in several districts.", "");
  out.push("## Summary", "");
  out.push(`- Institutions: ${plan.length}; with an official district after normalising: ${plan.filter((p) => p.next).length}`);
  out.push(`- Distinct (state, raw district) values: ${districtRows.length} (${counts(districtRows)})`);
  out.push(`- Distinct (state, city) values used where the district gave nothing: ${cityRows.length} (${counts(cityRows)})`);
  out.push(`- Distinct (state, official district) values after normalising: ${finalPairs.size}`);
  out.push(`- Values left unmapped: ${unresolved.length}, carried by ${unresolved.reduce((s, r) => s + r.n, 0)} institution entries`, "");
  out.push("Match types:", "");
  for (const [k, v] of Object.entries(MATCH_NOTE)) out.push(`- \`${k}\`: ${v}`);
  out.push("");

  out.push("## Unmapped values", "");
  out.push("| State | Field | Raw value | Why | Institutions |", "| --- | --- | --- | --- | ---: |");
  for (const r of unresolved) out.push(`| ${esc(r.state)} | ${r.field} | ${esc(r.raw)} | ${r.match} | ${r.n} |`);
  out.push("");

  const section = (title: string, list: Row[]) => {
    out.push(`## ${title}`, "");
    let state = "";
    for (const r of list) {
      if (r.state !== state) {
        state = r.state;
        out.push("", `### ${state}`, "", "| Raw value | Official district | Match | Institutions |", "| --- | --- | --- | ---: |");
      }
      out.push(`| ${esc(r.raw)} | ${r.district ? esc(r.district) : "(not mapped)"} | ${r.match} | ${r.n} |`);
    }
    out.push("");
  };
  section("District values from the council lists", districtRows);
  section("City values used where the district gave nothing", cityRows);

  const file = path.join(process.cwd(), "docs", "district-mapping.md");
  writeFileSync(file, out.join("\n").replace(/\n{3,}/g, "\n\n"));
  console.log(`Wrote ${file}: ${districtRows.length} district values, ${cityRows.length} city values, ${unresolved.length} unmapped`);
}

main()
  .then(() => process.exit(0))
  .catch((e) => {
    console.error(e);
    process.exit(1);
  });
