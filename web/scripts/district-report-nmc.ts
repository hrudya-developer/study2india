/**
 * Writes docs/district-mapping-nmc.md: how the district and town of every college on the NMC lists
 * (read from the college's name, as those lists have no address column) and on the NCH list (read
 * from its address line) were worked out, what each method placed, and every name or address
 * left unplaced. Read-only. Run with `npx tsx scripts/district-report-nmc.ts` against a loaded
 * database (DATABASE_URL) for the coverage tables; the names and addresses come from the
 * embedded lists.
 */
import "dotenv/config";
import { writeFileSync } from "node:fs";
import path from "node:path";
import { sql } from "drizzle-orm";
import { rows } from "../lib/db";
import { NMC_FILES, COUNCIL_FILES } from "../lib/db/seed-data.generated";
import { stateCode } from "../lib/bootstrap";
import { STATES } from "../data/reference";
import { DISTRICT_NORMALISER_VERSION, placeFromAddress, placeFromCollegeName, type TextPlace } from "../lib/districts";

type NamedRow = { code: string; name: string; state: string; address?: string | null };
type Source = { title: string; url: string; retrieved: string; field: "name" | "address"; rows: NamedRow[] };

/**
 * District coverage measured on a fresh load of the same lists with normaliser v1 (before names
 * and addresses were read), for the before/after table.
 */
const BEFORE: Record<string, [number, number]> = {
  mbbs: [16, 834],
  "md-ms": [17, 634],
  "dm-mch": [16, 219],
  "pg-diploma-medical": [11, 210],
  bhms: [1, 242],
  "md-homoeopathy": [1, 77],
};
const COURSE_LABEL: Record<string, string> = {
  mbbs: "MBBS",
  "md-ms": "MD/MS",
  "dm-mch": "DM/M.Ch",
  "pg-diploma-medical": "PG diploma (medical)",
  bhms: "BHMS",
  "md-homoeopathy": "MD (Homoeopathy)",
};

const METHOD_NOTE: Record<string, string> = {
  segment: "a part after the college's own name (\"…, Ernakulam\"), or the town at the end of the address",
  trailing: "the words after the name's last \"College\"/\"Hospital\"/\"Institute\" (\"Nandha Medical College & Hospital Erode\")",
  "district-mark": "a value marked as the district (\"Dist. Jalna\", \"Villupuram District\")",
  leading: "the town the name starts with, used only when no other part is a place (\"Coimbatore Medical College\")",
};
const REASON_NOTE: Record<string, string> = {
  "city-spans-districts": "metro city whose colleges lie in several districts (Bengaluru, Chennai, Hyderabad, Kolkata, Delhi)",
  ambiguous: "split district or place across several districts (Mumbai, Navi Mumbai, Burdwan, Midnapore, Imphal, Guwahati, Akbarpur)",
  conflict: "the text names places in two different districts (often a town and its pre-split district)",
  unknown: "no word read is an official district or a hand-checked alias or town (often the name carries only a founder's or trust's name)",
  "other-state": "the place named is a district of another state",
  none: "the text names no place at all",
};

const esc = (s: string) => s.replace(/\|/g, "\\|").replace(/\s+/g, " ").trim();
const stateNames = new Map(STATES.map((s) => [s.code, s.name]));
const reasonOf = (p: TextPlace) => (p.match === null ? "none" : (p.match as string));

async function main() {
  const sources: Source[] = [];
  for (const file of NMC_FILES) {
    const d = file.data as { source: { title: string; url: string; retrieved: string }; rows: NamedRow[]; institutions?: NamedRow[]; courses?: unknown };
    if ("courses" in d) sources.push({ ...d.source, field: "name", title: `${d.source.title} (institutions not on the MBBS list)`, rows: d.institutions ?? [] });
    else sources.push({ ...d.source, field: "name", rows: d.rows });
  }
  for (const file of COUNCIL_FILES) {
    const d = file.data as { council: string; sources: { title: string; url: string; retrieved: string }[]; rows: (NamedRow & { district?: string | null; city?: string | null })[] };
    if (d.council !== "NCH") continue;
    sources.push({ ...d.sources[0], field: "address", rows: d.rows.filter((r) => !r.district?.trim() && !r.city?.trim()) });
  }

  const out: string[] = [];
  out.push("# District mapping audit: NMC and NCH colleges", "");
  out.push(
    `Generated by \`scripts/district-report-nmc.ts\` (normaliser v${DISTRICT_NORMALISER_VERSION}). Matching code: \`placeFromCollegeName\` and ` +
      "`placeFromAddress` in lib/districts.ts; every place they find goes through `matchDistrict`, so only official district names, " +
      "hand-checked aliases and hand-checked towns in data/districts.ts are ever placed.",
    "",
  );
  out.push("## Sources", "");
  out.push(
    "- **NMC lists of colleges teaching MBBS and PG courses** (data/nmc/mbbs.json, data/nmc/pg.json). The rows as retrieved carry the college code, name, state, " +
      "university, management, year and seats: no address, city or district field. The official pages on nmc.org.in could not be reached from the build " +
      "environment (the proxy refused the host), so they were not re-checked for an address column. NMC's names often end with the town " +
      "(\"Government Medical College, Ernakulam\"), so the town is read from the name.",
    "- **NCH college permission status** (data/councils/nch.json): an address line for every college, no district or town column. The district and town are read from the address.",
    "- **NIRF rankings** (data/nirf): a city for every row, already placed through the normaliser. The NIRF-only institutions still without a district are all in metro cities (see below).",
    "",
  );
  out.push("## Method", "");
  out.push(
    "A name is read in the order written: the words after the college's own name, the parts after its commas, then bracketed former names; a value marked " +
      "\"Dist.\"/\"District\" anywhere counts too. The first place named decides: when it is a metro city or a split district (\"Akbarpur, Kanpur\": " +
      "Akbarpur is the seat of both Ambedkar Nagar and Kanpur Dehat) nothing is placed, otherwise every place found must agree on one district, and a disagreement places nothing. " +
      "Roads named after a town (\"Thuraiyur Road\") are skipped. Only when the name gives no place at all does a town it starts with count.",
    "",
    "An address is read from the end: the district marked \"Dist.\"/\"District\", and the town in the last part once the PIN and state are dropped (earlier " +
      "parts only while the later ones are not places, and only the part just before a marked district). A marked district and the town must agree.",
    "",
    "The town found fills an empty city; a metro city that cannot be placed in one district still fills the city. The loaders write both on insert and " +
      "fill them only where empty on update; the boot-time normaliser (planDistricts) applies the same reading to databases loaded earlier, after the council " +
      "district columns, the institution's city and the councils' city columns.",
    "",
  );
  for (const [k, v] of Object.entries(METHOD_NOTE)) out.push(`- \`${k}\`: ${v}`);
  out.push("");

  out.push("## Summary per source", "");
  out.push("| Source | Read from | Colleges | District placed | By method | Town found | Not placed |", "| --- | --- | ---: | ---: | --- | ---: | ---: |");
  const details: { source: Source; placed: { r: NamedRow; p: TextPlace }[]; unplaced: { r: NamedRow; p: TextPlace }[] }[] = [];
  for (const s of sources) {
    const results = s.rows.map((r) => ({ r, p: s.field === "name" ? placeFromCollegeName(stateCode(r.state), r.name) : placeFromAddress(stateCode(r.state), r.address, r.name) }));
    const placed = results.filter((x) => x.p.district);
    const unplaced = results.filter((x) => !x.p.district);
    const byMethod = new Map<string, number>();
    for (const x of placed) byMethod.set(x.p.method!, (byMethod.get(x.p.method!) ?? 0) + 1);
    const methods = [...byMethod].sort((a, b) => b[1] - a[1]).map(([k, v]) => `${k} ${v}`).join(", ");
    const towns = results.filter((x) => x.p.city).length;
    out.push(`| ${esc(s.title)} | ${s.field === "name" ? "college name" : "address field"} | ${results.length} | ${placed.length} | ${methods} | ${towns} | ${unplaced.length} |`);
    details.push({ source: s, placed, unplaced });
  }
  out.push("");

  out.push("## District coverage by course", "");
  out.push("Institutions offering the course in the database with an official district, on a fresh load of all lists.", "");
  out.push("| Course | Before (normaliser v1) | After | With a city |", "| --- | ---: | ---: | ---: |");
  const cov = await rows<{ slug: string; total: number; with_district: number; with_city: number }>(sql`
    select c.slug, count(distinct i.id) total,
      count(distinct case when i.district is not null then i.id end) with_district,
      count(distinct case when i.city is not null and i.city <> '' then i.id end) with_city
    from offerings o join courses c on c.id = o.course_id join institutions i on i.id = o.institution_id
    where c.slug in ('mbbs', 'md-ms', 'dm-mch', 'pg-diploma-medical', 'bhms', 'md-homoeopathy') group by c.slug`);
  const pct = (a: number, b: number) => (b ? `${Math.round((100 * a) / b)}%` : "-");
  for (const slug of Object.keys(BEFORE)) {
    const c = cov.find((x) => x.slug === slug);
    if (!c) continue;
    const [b, bt] = BEFORE[slug];
    out.push(`| ${COURSE_LABEL[slug]} | ${b} of ${bt} (${pct(b, bt)}) | ${Number(c.with_district)} of ${Number(c.total)} (${pct(Number(c.with_district), Number(c.total))}) | ${Number(c.with_city)} |`);
  }
  const [nirf] = await rows<{ total: number; with_district: number; with_city: number }>(sql`
    select count(*) total, sum(i.district is not null) with_district, sum(i.city is not null and i.city <> '') with_city from institutions i
    where exists (select 1 from institution_identifiers x where x.institution_id = i.id and x.scheme = 'nirf')
      and not exists (select 1 from offerings o where o.institution_id = i.id)`);
  if (nirf) out.push(`| NIRF-only institutions (no course list) | unchanged | ${Number(nirf.with_district)} of ${Number(nirf.total)} (${pct(Number(nirf.with_district), Number(nirf.total))}) | ${Number(nirf.with_city)} |`);
  out.push("");
  const nirfLeft = await rows<{ state_code: string | null; city: string | null; n: number }>(sql`
    select i.state_code, i.city, count(*) n from institutions i
    where exists (select 1 from institution_identifiers x where x.institution_id = i.id and x.scheme = 'nirf')
      and not exists (select 1 from offerings o where o.institution_id = i.id) and i.district is null
    group by i.state_code, i.city order by n desc`);
  out.push(
    "NIRF-only institutions without a district, by the city NIRF gives: " +
      nirfLeft.map((r) => `${r.city ?? "(no city)"} (${stateNames.get(r.state_code ?? "") ?? r.state_code}) ${Number(r.n)}`).join(", ") +
      ". These are metro cities left unplaced on purpose.",
    "",
  );

  out.push("## MBBS colleges with a district, by state", "");
  out.push("| State | MBBS colleges | With a district | Share |", "| --- | ---: | ---: | ---: |");
  const byState = await rows<{ state_code: string | null; total: number; placed: number }>(sql`
    select i.state_code, count(distinct i.id) total, count(distinct case when i.district is not null then i.id end) placed
    from offerings o join courses c on c.id = o.course_id and c.slug = 'mbbs' join institutions i on i.id = o.institution_id
    group by i.state_code order by total desc, i.state_code`);
  for (const r of byState) out.push(`| ${stateNames.get(r.state_code ?? "") ?? "(no state)"} | ${Number(r.total)} | ${Number(r.placed)} | ${pct(Number(r.placed), Number(r.total))} |`);
  out.push("");

  out.push("## Not placed", "");
  out.push("Why a name or address placed no district:", "");
  for (const [k, v] of Object.entries(REASON_NOTE)) out.push(`- \`${k}\`: ${v}`);
  out.push("");
  for (const d of details) {
    out.push(`### ${esc(d.source.title)}`, "");
    const counts = new Map<string, number>();
    for (const x of d.unplaced) counts.set(reasonOf(x.p), (counts.get(reasonOf(x.p)) ?? 0) + 1);
    out.push(`${d.unplaced.length} of ${d.source.rows.length} not placed: ${[...counts].sort((a, b) => b[1] - a[1]).map(([k, v]) => `${k} ${v}`).join(", ") || "none"}.`, "");
    if (!d.unplaced.length) continue;
    out.push(`| State | ${d.source.field === "name" ? "College name" : "Address"} | Why | Text read | Town kept as city |`, "| --- | --- | --- | --- | --- |");
    const sorted = [...d.unplaced].sort((a, b) => a.r.state.localeCompare(b.r.state) || reasonOf(a.p).localeCompare(reasonOf(b.p)) || a.r.name.localeCompare(b.r.name));
    for (const x of sorted) {
      const text = d.source.field === "name" ? x.r.name : (x.r.address ?? "").slice(x.r.address?.toLowerCase().startsWith(x.r.name.toLowerCase()) ? x.r.name.length : 0).replace(/^[\s,]+/, "");
      const why = x.p.match === "conflict" ? `conflict (${x.p.conflicting?.join(" / ")})` : reasonOf(x.p);
      out.push(`| ${esc(x.r.state)} | ${esc(text)} | ${why} | ${x.p.raw ? esc(x.p.raw) : ""} | ${x.p.city ? esc(x.p.city) : ""} |`);
    }
    out.push("");
  }

  out.push("## Placed by a hand-checked town or alias, or from the start of the name", "");
  out.push("Every placement that did not come from an official district name as written, for review.", "");
  out.push("| Source | State | Text | Method | Read as | District |", "| --- | --- | --- | --- | --- | --- |");
  for (const d of details) {
    const label = d.source.field === "name" ? (d.source.title.includes("PG") ? "NMC PG" : "NMC MBBS") : "NCH";
    for (const x of d.placed) {
      if (x.p.match === "exact" || x.p.match === "normalised") {
        if (x.p.method !== "leading") continue;
      }
      const text = d.source.field === "name" ? x.r.name : (x.r.address ?? "").slice(x.r.name.length).replace(/^[\s,]+/, "");
      out.push(`| ${label} | ${esc(x.r.state)} | ${esc(text)} | ${x.p.method} (${x.p.match}) | ${esc(x.p.raw ?? "")} | ${x.p.district} |`);
    }
  }
  out.push("");

  out.push("## Caveats", "");
  out.push(
    "- Names and addresses that give a district as it was before a split are placed in the district of that name: Andhra Pradesh's 2022 " +
      "reorganisation (a college named \"…, Chittoor\" or \"Krishna Dist.\" may now lie in Tirupati or NTR), and Telangana addresses giving \"Medak\" " +
      "for mandals now in Siddipet or Sangareddy. Where the same text also names a town in the newer district, the two disagree and nothing is placed.",
    "- Metro cities are not placed from a name or address alone: the colleges named \"…, Bangalore\" include ones in Bengaluru Rural (Hoskote, " +
      "Nelamangala) as well as Bengaluru Urban, and those named \"…, Chennai\" include ones in Chengalpattu, Tiruvallur and Kancheepuram. Their " +
      "district needs each college's own address, which none of these lists gives.",
    "",
  );

  const file = path.join(process.cwd(), "docs", "district-mapping-nmc.md");
  writeFileSync(file, out.join("\n").replace(/\n{3,}/g, "\n\n"));
  console.log(`Wrote ${file}`);
}

main()
  .then(() => process.exit(0))
  .catch((e) => {
    console.error(e);
    process.exit(1);
  });
